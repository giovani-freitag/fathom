#!/usr/bin/env node
/**
 * Emits the emoji a reader can pin, as a module the picker reads.
 *
 * Generated rather than depended on: the source package carries every locale
 * and fifty megabytes with them, and what the picker needs is one glyph, one
 * name and the words somebody might look for it by. Run by
 * `npm run build:emoji`, and checked by an arch test so it cannot drift from
 * the package it was generated out of.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const NAMED = process.argv.slice(2).find((one) => !one.startsWith('--'));
const OUT = NAMED ?? join(ROOT, 'src', 'shared', 'core', 'emoji-catalogue.generated.ts');

/**
 * The groups the picker offers as tabs, in the order a phone shows them.
 *
 * Components are left out: a skin tone on its own and a regional indicator are
 * pieces other emoji are built from, not marks anybody would pin to a chart.
 */
const TABS = [0, 1, 3, 4, 5, 6, 7, 8, 9];

function readPackage(path) {
    return JSON.parse(readFileSync(join(ROOT, 'node_modules', 'emojibase-data', path), 'utf8'));
}

/**
 * Every word one emoji can be found by, deduplicated and lowercased.
 *
 * The name is in here as well as the tags, because a reader types what they
 * would call the thing and the tags alone often do not include it.
 */
function collectTerms(entry) {
    const words = [...entry.label.split(/[\s-]+/), ...entry.tags ?? []]
        .map((one) => one.toLowerCase().replace(/[^a-z0-9]/g, ''))
        .filter((one) => one !== '');
    return [...new Set(words)].join(' ');
}

const data = readPackage(join('en', 'data.json'));
const kept = data
    .filter((entry) => TABS.includes(entry.group))
    .sort((one, other) => one.order - other.order);

/** One string as the project writes them, which is in single quotes. */
function quote(value) {
    return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

const rows = kept
    .map((entry) => {
        const cells = [quote(entry.emoji), quote(entry.label), quote(collectTerms(entry)), String(entry.group)];
        return `    [${cells.join(', ')}],`;
    })
    .join('\n');

const module = `// Generated by scripts/build-emoji-catalogue.mjs. Do not edit.
// Run \`npm run build:emoji\` after bumping emojibase-data.

/** The tabs the picker offers, in the order a phone shows them. */
export const EMOJI_GROUPS = [${TABS.join(', ')}] as const;

/** One emoji: its glyph, its name, the words it answers to, and its group. */
export type EmojiRow = readonly [glyph: string, label: string, terms: string, group: number];

export const EMOJI_CATALOGUE: readonly EmojiRow[] = [
${rows}
];
`;

writeFileSync(OUT, module);
console.log(`Wrote ${OUT} (${String(kept.length)} emoji, ${String(module.length)} characters)`);
